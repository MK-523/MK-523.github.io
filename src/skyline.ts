export function createSkylineTexture(width = 1024) {
  const pixels = new Uint8Array(width * ridges.length * 4);
  ridges.forEach((points, row) => {
    let segment = 0;
    for (let x = 0; x < width; x++) {
      const u = x / (width - 1);
      while (segment < points.length - 2 && u > points[segment + 1][0])
        segment++;
      const [x0, y0] = points[segment];
      const [x1, y1] = points[segment + 1];
      const height = y0 + ((u - x0) / (x1 - x0)) * (y1 - y0);
      const offset = (row * width + x) * 4;
      pixels[offset] = Math.round(height * 255);
      pixels[offset + 3] = 255;
    }
  });
  return { pixels, width, height: ridges.length };
}
